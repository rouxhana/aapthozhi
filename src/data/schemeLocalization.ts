/**
 * Returns a fully localized SchemeInfo object for the given scheme and language.
 * Falls back gracefully to Hindi or English if a specific dialect string is missing.
 */
export function getLocalizedScheme(scheme: SchemeInfo, langCode: LanguageCode): SchemeInfo {
  const schemeDict = SCHEME_LOCALIZATIONS[scheme.id];
  if (!schemeDict) return scheme;

  // Exact language match or fallback
  const loc = schemeDict[langCode] || (langCode === 'hinglish' ? schemeDict['hi'] : undefined);
  if (!loc) return scheme;

  return {
    ...scheme,
    title: loc.title || scheme.title,
    tagline: loc.tagline || scheme.tagline,
    description: loc.description || scheme.description,
    benefits: loc.benefits && loc.benefits.length > 0 ? loc.benefits : scheme.benefits,
    eligibility: loc.eligibility && loc.eligibility.length > 0 ? loc.eligibility : scheme.eligibility,
    whatToSayText: loc.whatToSayText || scheme.whatToSayText,
    slowExplanationSteps:
      loc.slowExplanationSteps && loc.slowExplanationSteps.length > 0
        ? loc.slowExplanationSteps
        : scheme.slowExplanationSteps,
  };
}
